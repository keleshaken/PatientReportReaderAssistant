def questions() -> list[dict]:
    return json.loads((ROOT / "data" / "eval" / "questions.json").read_text(encoding="utf-8"))


def prepare_document(filename: str, embedder: E5Embedder, client: TextClient | None = None):
    data = (ROOT / "data" / "sample_docs" / filename).read_bytes()
    pages = extract_document(data, filename, client)
    chunks, lines = split_pages(pages)
    temp = tempfile.TemporaryDirectory(prefix="patient-eval-")
    store = VectorStore(Path(temp.name))
    store.add(chunks, embedder.passages([x.text for x in chunks]))
    return temp, Retriever(embedder, store), lines


def update_results(metric: str, value: str) -> None:
    path = ROOT / "eval" / "results.md"
    rows = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("| ") and " | " in line and not line.startswith("| Metric"):
                cells = [x.strip() for x in line.strip("|").split("|")]
                if len(cells) == 2 and cells[0] != "---":
                    rows[cells[0]] = cells[1]
    rows[metric] = value
    header = "# Evaluation results\n\nThese values are generated by the scripts against the synthetic data. " \
             "An unrun value is not a measured result.\n\n| Metric | Result |\n| --- | --- |\n"
    path.write_text(header + "".join(f"| {key} | {val} |\n" for key, val in rows.items()), encoding="utf-8")
